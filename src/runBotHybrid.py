import sys
import os
import time
import threading
from datetime import datetime
import pytz

os.environ.setdefault("PYTHONIOENCODING", "utf-8")
if sys.stdout.encoding and sys.stdout.encoding.lower() != "utf-8":
    import io
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace")
    sys.stderr = io.TextIOWrapper(sys.stderr.buffer, encoding="utf-8", errors="replace")

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
sys.path.append(BASE_DIR)

# Fix CWD to src/ so relative paths (token files, state files) resolve correctly
os.chdir(BASE_DIR)

# Per-bot log file: logs/hybrid_YYYYMMDD.log
os.environ.setdefault("BOT_NAME", "hybrid")

from logger_config import get_logger
from vam_hybrid import VAMHybridEngine

logger = get_logger()
IST = pytz.timezone("Asia/Kolkata")

STOP_TIME_HOUR   = 15
STOP_TIME_MINUTE = 25


def should_stop():
    now = datetime.now(IST)
    return now.hour > STOP_TIME_HOUR or (
        now.hour == STOP_TIME_HOUR and now.minute >= STOP_TIME_MINUTE
    )


def stop_watcher(engine):
    logger.info("[runBotHybrid] Stop watcher started - will stop at 15:25 IST")
    while True:
        time.sleep(30)
        if should_stop():
            logger.info("[runBotHybrid] 15:25 IST reached - stopping hybrid engine")
            try:
                engine._shutdown()
            except Exception as e:
                logger.error("[runBotHybrid] Shutdown error: %s", e)
            time.sleep(2)
            os._exit(0)


def main():
    logger.info("=== VAM Hybrid Bot Starting ===")
    logger.info("[runBotHybrid] Token must already be generated by runBot.py")

    for f in ["fyers_appid.txt", "fyers_token.txt"]:
        if not os.path.exists(f):
            logger.error("[runBotHybrid] Missing %s - start runBot.py first", f)
            sys.exit(1)

    app_id    = open("fyers_appid.txt").read().strip()
    raw_token = open("fyers_token.txt").read().strip()
    ws_token  = "%s:%s" % (app_id, raw_token)

    engine = VAMHybridEngine(ws_token=ws_token)

    watcher = threading.Thread(target=stop_watcher, args=(engine,), daemon=True)
    watcher.start()
    logger.info("[runBotHybrid] Stop watcher running")

    logger.info("[runBotHybrid] Starting VAMHybridEngine...")
    try:
        engine.start()
    except KeyboardInterrupt:
        logger.info("[runBotHybrid] KeyboardInterrupt - stopping")
        try:
            engine._shutdown()
        except Exception:
            pass

    logger.info("=== VAM Hybrid Bot Stopped ===")


if __name__ == "__main__":
    main()
