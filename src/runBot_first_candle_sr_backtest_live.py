"""Launcher for the uploaded First Candle High/Low retest live engine.

Runs alongside the VAM bot and shares fyers_appid.txt / fyers_token.txt.
By default this launcher does NOT generate a token; it waits for today's token
from the VAM launcher and then imports Engine from first_candle_sr_backtest_live.py.

Put this file and first_candle_sr_backtest_live.py in the SAME directory as the
shared token files. Run before 09:15 IST where possible:
    python runBot_first_candle_sr_backtest_live.py

Set GENERATE_TOKEN=True only when deliberately running standalone.
"""
from __future__ import annotations
import os
import sys
import time
import threading
from datetime import datetime
from pathlib import Path
import pytz

os.environ.setdefault("PYTHONIOENCODING", "utf-8")
if getattr(sys.stdout, "encoding", None) and sys.stdout.encoding.lower() != "utf-8":
    import io
    if hasattr(sys.stdout, "buffer"):
        sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace")
    if hasattr(sys.stderr, "buffer"):
        sys.stderr = io.TextIOWrapper(sys.stderr.buffer, encoding="utf-8", errors="replace")

BASE_DIR = Path(__file__).resolve().parent
sys.path.insert(0, str(BASE_DIR))
os.chdir(BASE_DIR)
os.environ.setdefault("BOT_NAME", "first_candle_sr_backtest_live")
IST = pytz.timezone("Asia/Kolkata")
STOP_HOUR, STOP_MIN = 15, 25
GENERATE_TOKEN = False
TOKEN_WAIT_SECS = 15 * 60
TOKEN_POLL_SECS = 15


def _token_fresh() -> bool:
    path = BASE_DIR / "fyers_token.txt"
    try:
        modified = datetime.fromtimestamp(path.stat().st_mtime, IST)
        return modified.date() == datetime.now(IST).date() and path.stat().st_size > 0
    except OSError:
        return False


def ensure_token() -> None:
    if GENERATE_TOKEN:
        try:
            from generate_TOTP_Token import GenerateTOTPToken
            if not GenerateTOTPToken():
                raise RuntimeError("TOTP generation returned False")
            print("FYERS token generated by First Candle Backtest launcher.")
        except Exception as exc:
            print(f"Token generation failed ({exc}); falling back to shared token files.")
    deadline = time.time() + TOKEN_WAIT_SECS
    while not _token_fresh() and time.time() < deadline:
        print("Waiting for today's shared token (expected from the VAM bot)...")
        time.sleep(TOKEN_POLL_SECS)
    if not _token_fresh():
        print("WARNING: shared token was not refreshed today; authentication may fail.")


def main() -> None:
    print("=== Uploaded First Candle High/Low SR live engine (dry-run by default) ===")
    if datetime.now(IST).weekday() >= 5:
        print("Today is a weekend in IST. Exiting.")
        return
    ensure_token()
    from first_candle_sr_backtest_live import Engine, setup_logging
    setup_logging()
    engine = Engine()

    def watcher() -> None:
        while True:
            time.sleep(30)
            now = datetime.now(IST)
            if now.hour > STOP_HOUR or (now.hour == STOP_HOUR and now.minute >= STOP_MIN):
                print("15:25 IST reached. Requesting graceful stop / open-position reconciliation.")
                engine.request_stop()
                return

    threading.Thread(target=watcher, daemon=True, name="FirstCandleSRBacktestStopWatcher").start()
    print("Stop watcher running (15:25 IST). Shared token mode; no token regeneration by default.")
    engine.run()


if __name__ == "__main__":
    main()
