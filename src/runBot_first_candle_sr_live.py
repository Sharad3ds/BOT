"""Launcher for the First Candle High/Low S/R live polling engine.

Runs alongside other bots and SHARES fyers_appid.txt / fyers_token.txt.
By default, it does not regenerate a token: the VAM launcher is expected to
refresh today's token and this launcher simply reads the shared token files.

Place this launcher and first_candle_sr_poll_live.py in the same directory as
the VAM bot and shared token files. Start before 09:15 IST to capture the
opening candle:
    python runBot_first_candle_sr_live.py

Set GENERATE_TOKEN=True only when running standalone and you explicitly want
this launcher to call generate_TOTP_Token.GenerateTOTPToken().
"""
from __future__ import annotations

import os
import sys
import time
import threading
from datetime import datetime
from pathlib import Path

import pytz

os.environ.setdefault("PYTHONIOENCODING", "utf-8")
if getattr(sys.stdout, "encoding", None) and sys.stdout.encoding.lower() != "utf-8":
    import io
    if hasattr(sys.stdout, "buffer"):
        sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace")
    if hasattr(sys.stderr, "buffer"):
        sys.stderr = io.TextIOWrapper(sys.stderr.buffer, encoding="utf-8", errors="replace")

BASE_DIR = Path(__file__).resolve().parent
sys.path.insert(0, str(BASE_DIR))
os.chdir(BASE_DIR)  # Shared token/state/log paths are relative to the common bot directory.
os.environ.setdefault("BOT_NAME", "first_candle_sr_live")

IST = pytz.timezone("Asia/Kolkata")
STOP_HOUR, STOP_MIN = 15, 25  # Stop after the strategy's 15:20 EOD exit.
GENERATE_TOKEN = False       # False = use today's token created by the VAM launcher.
TOKEN_WAIT_SECS = 15 * 60
TOKEN_POLL_SECS = 15


def _token_fresh() -> bool:
    """True when the shared token file exists, is non-empty, and was touched today IST."""
    path = BASE_DIR / "fyers_token.txt"
    try:
        modified = datetime.fromtimestamp(path.stat().st_mtime, IST)
        return modified.date() == datetime.now(IST).date() and path.stat().st_size > 0
    except OSError:
        return False


def ensure_token() -> None:
    if GENERATE_TOKEN:
        try:
            from generate_TOTP_Token import GenerateTOTPToken
            if not GenerateTOTPToken():
                raise RuntimeError("TOTP generation returned False")
            print("FYERS token generated by First Candle SR launcher.")
        except Exception as exc:
            print(f"Token generation failed ({exc}); will check the shared token files instead.")

    deadline = time.time() + TOKEN_WAIT_SECS
    while not _token_fresh() and time.time() < deadline:
        print("Waiting for today's shared FYERS token (expected from the VAM bot)...")
        time.sleep(TOKEN_POLL_SECS)
    if not _token_fresh():
        print("WARNING: shared token was not refreshed today. Proceeding with the existing file; authentication may fail.")


def main() -> None:
    print("=== First Candle High/Low Retest Bot (dry-run by default) starting ===")
    if datetime.now(IST).weekday() >= 5:
        print("Today is a weekend in IST. No market session; exiting.")
        return

    ensure_token()
    # Import the actual engine class defined in first_candle_sr_poll_live.py.
    # Keep both files in the same directory so Pylance and Python can resolve it.
    from first_candle_sr_poll_live import LiveBot, setup_logging

    setup_logging()
    engine = LiveBot()

    def watcher() -> None:
        while True:
            time.sleep(30)
            now = datetime.now(IST)
            if now.hour > STOP_HOUR or (now.hour == STOP_HOUR and now.minute >= STOP_MIN):
                print("15:25 IST reached. Requesting graceful engine shutdown.")
                engine.request_stop()
                return

    threading.Thread(target=watcher, daemon=True, name="FirstCandleSRStopWatcher").start()
    print("Stop watcher running (requests graceful shutdown at 15:25 IST).")
    engine.run()


if __name__ == "__main__":
    main()
