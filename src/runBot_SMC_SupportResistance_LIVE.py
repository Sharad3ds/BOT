"""
Launcher for the Support/Resistance Reversal LIVE bot
(SMC_SupportResistance_LIVE_FyersV3.Engine).

Runs ALONGSIDE the other bots, SHARING the same Fyers token files.

By default it does NOT regenerate the token - the VAM runBot generates it,
and this bot just reads the shared fyers_appid.txt / fyers_token.txt.

Run it from the SAME directory as your VAM bot, with:
    SMC_SupportResistance_LIVE_FyersV3.py
    expiry_resolver.py
    fyers_appid.txt
    fyers_token.txt

Run:
    python runBot_SMC_SupportResistance_LIVE.py

Set GENERATE_TOKEN=True below only if this process should log in on its own.
"""

import sys
import os
import time
import threading
import io
from datetime import datetime

import pytz

os.environ.setdefault("PYTHONIOENCODING", "utf-8")

if sys.stdout.encoding and sys.stdout.encoding.lower() != "utf-8":
    sys.stdout = io.TextIOWrapper(
        sys.stdout.buffer, encoding="utf-8", errors="replace"
    )
    sys.stderr = io.TextIOWrapper(
        sys.stderr.buffer, encoding="utf-8", errors="replace"
    )

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
sys.path.append(BASE_DIR)
os.chdir(BASE_DIR)  # token/state/log paths resolve here

os.environ.setdefault("BOT_NAME", "smc_sr_live")

IST = pytz.timezone("Asia/Kolkata")

STOP_HOUR, STOP_MIN = 15, 25
GENERATE_TOKEN = False  # True = this process logs in itself; False = use shared token


def _token_fresh():
    try:
        token_path = os.path.join(BASE_DIR, "fyers_token.txt")
        mt = datetime.fromtimestamp(os.path.getmtime(token_path), IST)

        return (
            mt.date() == datetime.now(IST).date()
            and os.path.getsize(token_path) > 0
        )

    except Exception:
        return False


def ensure_token():
    if GENERATE_TOKEN:
        try:
            from generate_TOTP_Token import GenerateTOTPToken

            if not GenerateTOTPToken():
                print("TOTP generation failed - exiting")
                sys.exit(1)

            print("TOTP generated by SMC S/R live launcher.")

        except Exception as e:
            print(
                f"Token generation unavailable ({e}); "
                "falling back to shared token files"
            )

    # Wait up to 15 minutes for the VAM bot to write today's shared token.
    deadline = time.time() + 900

    while not _token_fresh() and time.time() < deadline:
        print(
            "Waiting for today's shared token "
            "(generated by the VAM bot)..."
        )
        time.sleep(15)

    if not _token_fresh():
        print(
            "WARNING: shared token not refreshed today - "
            "proceeding; authentication may fail."
        )


def main():
    print("=== Support/Resistance Reversal SMC LIVE starting ===")

    ensure_token()

    from SMC_SupportResistance_LIVE_FyersV3 import Engine

    engine = Engine()

    def watcher():
        while True:
            time.sleep(30)

            now = datetime.now(IST)

            if (
                now.hour > STOP_HOUR
                or (now.hour == STOP_HOUR and now.minute >= STOP_MIN)
            ):
                print("Stop time reached (15:25 IST).")

                try:
                    engine._shutdown()
                except Exception as e:
                    print(f"shutdown err: {e}")

                os._exit(0)

    threading.Thread(target=watcher, daemon=True).start()

    print("Stop watcher running (stops 15:25 IST).")
    print("SMC S/R live engine started.")

    engine.run()


if __name__ == "__main__":
    main()
