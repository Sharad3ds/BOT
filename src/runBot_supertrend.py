"""
Launcher for the Supertrend 10-min option dry-run bot (SupertrendPoll.Engine).
Runs ALONGSIDE the VAM poll bot, SHARING the same Fyers token files in this dir.

By default it does NOT regenerate the token — the VAM runBot generates it, and
this bot just reads the shared fyers_appid.txt / fyers_token.txt. (Supertrend is
DRY-RUN + read-only, so two clients on one token is safe.)

Run it from the SAME directory as your VAM bot (so the token files are shared),
with SupertrendPoll.py alongside:
    python runBot_supertrend.py
Set GENERATE_TOKEN=True below only if this process should log in on its own
(e.g. running standalone without the VAM bot).
"""
import sys, os, time, threading
from datetime import datetime
import pytz

os.environ.setdefault("PYTHONIOENCODING", "utf-8")
if sys.stdout.encoding and sys.stdout.encoding.lower() != "utf-8":
    import io
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace")
    sys.stderr = io.TextIOWrapper(sys.stderr.buffer, encoding="utf-8", errors="replace")

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
sys.path.append(BASE_DIR)
os.chdir(BASE_DIR)                       # token/state/log paths resolve here (shared with VAM if same dir)
os.environ.setdefault("BOT_NAME", "supertrend")   # separate log file from the VAM bot

IST = pytz.timezone("Asia/Kolkata")
STOP_HOUR, STOP_MIN = 15, 25             # stop shortly after the 15:20 EOD exit
GENERATE_TOKEN = False                   # True = this process logs in itself; False = use shared token

def _token_fresh():
    try:
        mt = datetime.fromtimestamp(os.path.getmtime("fyers_token.txt"), IST)
        return mt.date() == datetime.now(IST).date() and os.path.getsize("fyers_token.txt") > 0
    except Exception:
        return False

def ensure_token():
    if GENERATE_TOKEN:
        try:
            from generate_TOTP_Token import GenerateTOTPToken
            if not GenerateTOTPToken():
                print("TOTP generation failed — exiting"); sys.exit(1)
            print("TOTP generated by Supertrend launcher.")
        except Exception as e:
            print(f"Token generation unavailable ({e}); falling back to shared token files")
    deadline = time.time() + 900   # wait up to 15 min for VAM to write TODAY's token
    while not _token_fresh() and time.time() < deadline:
        print("Waiting for today's shared token (generated by the VAM bot)...")
        time.sleep(15)
    if not _token_fresh():
        print("WARNING: shared token not refreshed today — proceeding; auth may fail.")

def main():
    print("=== Supertrend 10-min Option Bot (dry-run) starting ===")
    ensure_token()
    from SupertrendPoll import Engine
    engine = Engine()

    def watcher():
        while True:
            time.sleep(30)
            now = datetime.now(IST)
            if now.hour > STOP_HOUR or (now.hour == STOP_HOUR and now.minute >= STOP_MIN):
                try: engine._shutdown()
                except Exception as e: print(f"shutdown err: {e}")
                os._exit(0)
    threading.Thread(target=watcher, daemon=True).start()
    print("Stop watcher running (stops 15:25 IST).")
    engine.run()

if __name__ == "__main__":
    main()
